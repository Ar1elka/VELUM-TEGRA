package com.velumtegra.xuimobile.core.ssh

import com.velumtegra.xuimobile.core.model.CommandCompletion
import java.security.SecureRandom
import java.time.Duration

/** Where the 3x-ui panel accepts connections, as configured by its `webListen` setting. */
enum class XuiPanelExposure {
    /** Loopback only: reachable through an SSH tunnel, closed to the internet. */
    LOOPBACK,
    /** All addresses (empty, 0.0.0.0 or ::): open to the internet unless a firewall blocks it. */
    PUBLIC,
    /** One specific non-loopback address. */
    SPECIFIC,
}

data class XuiPanelAccessState(
    val listenAddress: String,
    val exposure: XuiPanelExposure,
    val panelPort: Int,
    val webBasePath: String,
    val tlsEnabled: Boolean,
    /** `/etc/x-ui/install-result.env` exists: the panel sign-in can be read without the operator. */
    val installResultPresent: Boolean,
    /** Addresses the panel port is actually bound to right now (`ss`), e.g. `127.0.0.1:43210`. */
    val boundAddresses: List<String>,
) {
    override fun toString(): String = "XuiPanelAccessState(exposure=$exposure, panelPort=$panelPort, " +
        "tlsEnabled=$tlsEnabled, installResultPresent=$installResultPresent, bound=$boundAddresses)"
}

sealed interface XuiPanelAccessRead {
    data class Observed(val state: XuiPanelAccessState) : XuiPanelAccessRead
    /** No 3x-ui binary at the standard path. */
    data object NotInstalled : XuiPanelAccessRead
    data object Unavailable : XuiPanelAccessRead
}

sealed interface XuiPanelChangeResult {
    data class Applied(val state: XuiPanelAccessState) : XuiPanelChangeResult
    data class Failed(val reason: String) : XuiPanelChangeResult
}

/** Panel sign-in generated by the app; [toString] never prints it. */
class XuiGeneratedPanelCredentials(val username: String, val password: String) {
    override fun toString(): String = "XuiGeneratedPanelCredentials(<redacted>)"

    companion object {
        private val random = SecureRandom()
        private const val ALPHABET = "abcdefghijkmnpqrstuvwxyzABCDEFGHJKLMNPQRSTUVWXYZ23456789"

        fun generate(): XuiGeneratedPanelCredentials =
            XuiGeneratedPanelCredentials("velum" + token(6).lowercase(), token(24))

        private fun token(length: Int) = buildString(length) { repeat(length) { append(ALPHABET[random.nextInt(ALPHABET.length)]) } }

        /** Only values the app generates are ever placed into a remote command line. */
        internal fun isSafe(value: String) = value.length in 4..64 && value.all { it in ALPHABET || it in "abcdefghijklmnopqrstuvwxyz0123456789" }
    }
}

/**
 * Reads and changes who may reach the 3x-ui panel, using only the official `x-ui setting` CLI.
 * Changing the listen address or the sign-in restarts `x-ui` (Xray clients reconnect within seconds).
 */
object XuiPanelAccessControl {
    private const val NOT_INSTALLED_EXIT = 45
    private val readConfig = SshTransportConfig(
        channelOpenTimeout = Duration.ofSeconds(5),
        commandExecutionTimeout = Duration.ofSeconds(15),
        stdoutCaptureLimitBytes = 4096,
        stderrCaptureLimitBytes = 1024,
    )
    private val changeConfig = readConfig.copy(commandExecutionTimeout = Duration.ofSeconds(45))

    private const val XUI = "/usr/local/x-ui/x-ui"

    /** Prints the current state; shared by read and by every change (as its final verification). */
    private val STATE_SCRIPT = """
xui=$XUI
[ -x "${'$'}xui" ] || exit $NOT_INSTALLED_EXIT
listen=${'$'}("${'$'}xui" setting -getListen true 2>/dev/null | sed -n 's/^listenIP:[[:space:]]*//p' | head -n 1)
show=${'$'}("${'$'}xui" setting -show 2>/dev/null)
port=${'$'}(printf '%s\n' "${'$'}show" | sed -n 's/^port:[[:space:]]*//p' | head -n 1)
base=${'$'}(printf '%s\n' "${'$'}show" | sed -n 's/^webBasePath:[[:space:]]*//p' | head -n 1)
printf 'LISTEN=%s\nPORT=%s\nBASE=%s\n' "${'$'}listen" "${'$'}port" "${'$'}base"
if printf '%s\n' "${'$'}show" | grep -q 'secure with SSL'; then printf 'TLS=1\n'; fi
if [ -f /etc/x-ui/install-result.env ]; then printf 'RESULT=1\n'; fi
case "${'$'}port" in ''|*[!0-9]*) ;; *)
  i=0
  while [ "${'$'}i" -lt 20 ]; do
    bound=${'$'}(ss -Hltn "sport = :${'$'}port" 2>/dev/null | awk '{print ${'$'}4}')
    [ -n "${'$'}bound" ] && break
    [ "${'$'}{WAIT_BIND:-0}" = 1 ] || break
    i=${'$'}((i + 1)); sleep 0.5
  done
  printf '%s\n' "${'$'}bound" | awk 'NF {print "BOUND=" ${'$'}0}' ;;
esac
""".trimStart()

    suspend fun read(session: SshSessionHandle): XuiPanelAccessRead {
        if (!session.isOpen) return XuiPanelAccessRead.Unavailable
        val result = session.execute(RemoteCommand.create(STATE_SCRIPT, "xui-panel-access-read"), readConfig)
        if (result.dispatchState != CommandDispatchState.DISPATCHED) return XuiPanelAccessRead.Unavailable
        val completion = result.completion
        if (completion is CommandCompletion.ConfirmedFailure && completion.exitCode == NOT_INSTALLED_EXIT) {
            return XuiPanelAccessRead.NotInstalled
        }
        if (completion != CommandCompletion.ConfirmedSuccess || result.stdout.truncated) return XuiPanelAccessRead.Unavailable
        return parse(result.stdout.copyBytes().decodeToString())?.let { XuiPanelAccessRead.Observed(it) }
            ?: XuiPanelAccessRead.Unavailable
    }

    /** Loopback only (SSH tunnel). */
    suspend fun closeToInternet(session: SshSessionHandle): XuiPanelChangeResult =
        change(session, "\"\$xui\" setting -listenIP 127.0.0.1 >/dev/null", "xui-panel-close") {
            it.exposure == XuiPanelExposure.LOOPBACK && it.boundAddresses.isNotEmpty() &&
                it.boundAddresses.all(::isLoopbackBinding)
        }

    /** All IPv4 addresses, exactly as the official `x-ui` menu does when it clears the listen IP. */
    suspend fun openToInternet(session: SshSessionHandle): XuiPanelChangeResult =
        change(session, "\"\$xui\" setting -listenIP 0.0.0.0 >/dev/null", "xui-panel-open") {
            it.exposure == XuiPanelExposure.PUBLIC && it.boundAddresses.any { address -> !isLoopbackBinding(address) }
        }

    /**
     * Sets a new panel sign-in. The values are app-generated (letters/digits only), so they never need
     * shell quoting. When the installer's result file exists, its two sign-in lines are updated too so
     * that it keeps describing the real sign-in.
     */
    suspend fun resetSignIn(
        session: SshSessionHandle,
        credentials: XuiGeneratedPanelCredentials,
        resetTwoFactor: Boolean,
    ): XuiPanelChangeResult {
        require(XuiGeneratedPanelCredentials.isSafe(credentials.username) && XuiGeneratedPanelCredentials.isSafe(credentials.password)) {
            "Only app-generated sign-in values are accepted"
        }
        val twoFactor = if (resetTwoFactor) " -resetTwoFactor=true" else ""
        val update = "\"\$xui\" setting -username '${credentials.username}' -password '${credentials.password}'$twoFactor >/dev/null\n" +
            "f=/etc/x-ui/install-result.env\n" +
            "if [ -f \"\$f\" ] && [ ! -L \"\$f\" ]; then\n" +
            "  t=\$(mktemp /etc/x-ui/.install-result.XXXXXX)\n" +
            "  awk -v u='${credentials.username}' -v p='${credentials.password}' " +
            "'/^XUI_USERNAME=/{print \"XUI_USERNAME=\" u; next} /^XUI_PASSWORD=/{print \"XUI_PASSWORD=\" p; next} {print}' \"\$f\" >\"\$t\"\n" +
            "  chmod 600 \"\$t\" && mv -f \"\$t\" \"\$f\"\n" +
            "fi"
        return change(session, update, "xui-panel-reset-sign-in") { it.boundAddresses.isNotEmpty() }
    }

    private suspend fun change(
        session: SshSessionHandle,
        mutation: String,
        label: String,
        verified: (XuiPanelAccessState) -> Boolean,
    ): XuiPanelChangeResult {
        if (!session.isOpen) return XuiPanelChangeResult.Failed("SSH-сессия закрыта.")
        val script = "set -e\nxui=$XUI\n[ -x \"\$xui\" ] || exit $NOT_INSTALLED_EXIT\n" + mutation +
            "\nsystemctl restart x-ui\nsleep 1\nset +e\nWAIT_BIND=1\n" + STATE_SCRIPT
        val result = session.execute(RemoteCommand.create(script, label), changeConfig)
        if (result.dispatchState != CommandDispatchState.DISPATCHED) {
            return XuiPanelChangeResult.Failed("Команда не была отправлена на сервер.")
        }
        val completion = result.completion
        if (completion is CommandCompletion.ConfirmedFailure && completion.exitCode == NOT_INSTALLED_EXIT) {
            return XuiPanelChangeResult.Failed("3x-ui не найдена по стандартному пути $XUI.")
        }
        if (completion != CommandCompletion.ConfirmedSuccess || result.stdout.truncated) {
            return XuiPanelChangeResult.Failed("Сервер не подтвердил изменение. Проверьте состояние панели.")
        }
        val state = parse(result.stdout.copyBytes().decodeToString())
            ?: return XuiPanelChangeResult.Failed("Не удалось прочитать состояние панели после изменения.")
        return if (verified(state)) XuiPanelChangeResult.Applied(state)
        else XuiPanelChangeResult.Failed("Панель после перезапуска слушает не так, как ожидалось: ${state.boundAddresses.ifEmpty { listOf("нет") }.joinToString()}.")
    }

    internal fun parse(text: String): XuiPanelAccessState? {
        val bound = mutableListOf<String>()
        val values = HashMap<String, String>()
        for (line in text.lineSequence()) {
            val index = line.indexOf('=')
            if (index <= 0) continue
            val key = line.substring(0, index)
            val value = line.substring(index + 1).trim()
            if (key == "BOUND") bound += value else values[key] = value
        }
        val port = values["PORT"]?.toIntOrNull()?.takeIf { it in 1..65535 } ?: return null
        val listen = values["LISTEN"].orEmpty()
        val base = values["BASE"].orEmpty().ifEmpty { "/" }
        return XuiPanelAccessState(
            listenAddress = listen,
            exposure = exposureOf(listen),
            panelPort = port,
            webBasePath = if (base.startsWith('/')) base else "/$base",
            tlsEnabled = values["TLS"] == "1",
            installResultPresent = values["RESULT"] == "1",
            boundAddresses = bound,
        )
    }

    fun exposureOf(listen: String): XuiPanelExposure = when (listen.trim().removePrefix("[").removeSuffix("]").lowercase()) {
        "", "0.0.0.0", "::", "*" -> XuiPanelExposure.PUBLIC
        "127.0.0.1", "::1", "localhost" -> XuiPanelExposure.LOOPBACK
        else -> XuiPanelExposure.SPECIFIC
    }

    internal fun isLoopbackBinding(address: String): Boolean {
        val host = address.substringBeforeLast(':').removePrefix("[").removeSuffix("]")
        return host == "127.0.0.1" || host == "::1" || host.startsWith("127.")
    }
}
